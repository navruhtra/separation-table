// Status section for README.md, built from real test output. No number in it is typed by hand.
//   node scripts/status.mjs                    run the unit, fuzz, mutation and gate tests here, then rewrite the README block
//   node scripts/status.mjs --logs <dir>       read <dir>/{check,fuzz,mutate,gate,e2e,readers}.log instead of running
//                                      (tee each layer's output into <dir>; e2e needs a browser and a server)
//   add --summary                      write the block to $GITHUB_STEP_SUMMARY (or stdout) instead of README.md
// The block sits between the two status markers in README.md. A missing log reads "not run", never a guess.
import { execSync, spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync, appendFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { VERSION } from "../src/version.js";

const root = join(dirname(fileURLToPath(import.meta.url)), ".."), argv = process.argv.slice(2);
const logsAt = argv.includes("--logs") ? argv[argv.indexOf("--logs") + 1] : null;
const RUNS = { check: "node tests/check.mjs", fuzz: "node tests/fuzz.mjs 60 369", mutate: "node tests/mutate.mjs", gate: "python3 scripts/prep-images.py && node tests/bench-test.mjs --gate tests/baseline.json",
  readers: "node tests/readback.mjs .cache/readback > /dev/null && python3 -I tests/outside-readers.py .cache/readback" };

/** @returns {string | null} the output of one test layer */
function output(name) {
  if (logsAt) { const f = join(logsAt, `${name}.log`); return existsSync(f) ? readFileSync(f, "utf8") : null; }
  if (!RUNS[name]) return null; // e2e needs a browser and a server: pass --logs
  const r = spawnSync("sh", ["-c", RUNS[name]], { cwd: root, encoding: "utf8", maxBuffer: 1 << 26 });
  return (r.stdout || "") + (r.stderr || "") + (r.status ? `\nexit ${r.status}\n` : "");
}
const lines = (t, re) => t.split("\n").filter(l => re.test(l)).length;

/** One row per layer: what ran and what it reported, read from the output text. */
export function summarize(out) {
  const rows = [];
  const pass = (t, re) => re.test(t) && !/\bFAIL|FAILED|^exit [1-9]/m.test(t);
  const c = out.check;
  rows.push(["Unit and property (check.mjs)", c == null ? "not run" : `${lines(c, /^ok\b/)} checks passed, ${lines(c, /^FAIL\b/)} failed`, c == null ? null : pass(c, /^all passed$/m)]);
  const f = out.fuzz, fm = f && f.match(/fuzz: (\d+) random cases/);
  rows.push(["Fuzz (seeded random images and settings)", f == null ? "not run" : fm ? `${fm[1]} random cases` : "no summary line", f == null ? null : pass(f, /fuzz: \d+ random cases.*passed/)]);
  const m = out.mutate, mm = m && m.match(/mutation score: (\d+)\/(\d+)/);
  rows.push(["Mutation (planted bugs the tests must catch)", m == null ? "not run" : mm ? `${mm[1]} of ${mm[2]} planted bugs caught` : "no summary line", m == null ? null : !!mm && !/SURVIVED/.test(m)]);
  const g = out.gate, gm = g && g.match(/gate passed: (\d+) cases/);
  rows.push(["Regression gate (test images × palettes vs baseline.json)", g == null ? "not run" : gm ? `${gm[1]} cases within tolerance` : "gate failed", g == null ? null : !!gm]);
  const e = out.e2e;
  rows.push(["Browser end to end (e2e.cjs)", e == null ? "not run" : `${lines(e, /^ok\b/)} checks passed, ${lines(e, /^FAIL\b/)} failed`, e == null ? null : pass(e, /^all passed$/m)]);
  const rd = out.readers, skips = rd ? lines(rd, /^ok .*\(skipped\)$/) : 0;
  rows.push(["Outside readers (Ghostscript, libtiff, Pillow, psd-tools)", rd == null ? "not run" : `${lines(rd, /^ok\b/) - skips} checks passed, ${lines(rd, /^FAIL\b/)} failed${skips ? `, ${skips} readers not installed` : ""}`, rd == null ? null : pass(rd, /^all passed$/m)]);
  return rows;
}

export function block(rows, { commit, date }) {
  const mark = v => v == null ? "not run" : v ? "pass" : "FAIL";
  return [
    `Version ${VERSION}. Generated by \`node scripts/status.mjs\` from the test output of ${commit ? `commit ${commit}` : "this source tree"} on ${date}.`,
    "",
    "| Layer | Result | Output |",
    "|---|---|---|",
    ...rows.map(([layer, res, ok]) => `| ${layer} | ${mark(ok)} | ${res} |`),
    "",
    "Print fidelity is not measured yet. Every ΔE the tool shows is a model number until a measured press run is published.",
  ].join("\n");
}

const BEGIN = "<!-- status:begin (generated by status.mjs; do not edit by hand) -->", END = "<!-- status:end -->";
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = Object.fromEntries(["check", "fuzz", "mutate", "gate", "e2e", "readers"].map(n => [n, output(n)]));
  let commit = null; try {
    commit = execSync("git rev-parse --short HEAD", { cwd: root, encoding: "utf8" }).trim();
    if (!logsAt && execSync("git status --porcelain -- .", { cwd: root, encoding: "utf8" }).trim()) commit += " plus uncommitted changes";
  } catch { /* not a git checkout */ }
  const text = block(summarize(out), { commit, date: new Date().toISOString().slice(0, 10) });
  if (argv.includes("--summary")) {
    if (process.env.GITHUB_STEP_SUMMARY) appendFileSync(process.env.GITHUB_STEP_SUMMARY, `## Separation Table status\n\n${text}\n`); else console.log(text);
  } else {
    const f = join(root, "README.md"), s = readFileSync(f, "utf8"), a = s.indexOf(BEGIN), b = s.indexOf(END);
    if (a < 0 || b < a) throw new Error("README.md has no status markers");
    writeFileSync(f, s.slice(0, a + BEGIN.length) + "\n" + text + "\n" + s.slice(b));
    console.log(text);
  }
  if (summarize(out).some(r => r[2] === false)) process.exitCode = 1;
}
