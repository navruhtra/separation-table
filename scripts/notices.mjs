// @ts-check
// Third-party notices and file hashes, generated from the pins in vendor-pins.mjs. No license text is typed by hand.
//   node scripts/notices.mjs            write THIRD-PARTY-NOTICES.md (license texts from .cache/node_modules) and src/vendor.sha256
//   node scripts/notices.mjs --check    fail if either file is out of date, or a file in src/vendor/ or src/models/ differs from its pin
//   add --models require        (with --check) every model must be present too; default: check the models that are present
// src/vendor.sha256 sits next to vendor/ and models/ and is in sha256sum format, so `sha256sum -c vendor.sha256` in src/ checks it without Node.
// After fetch-vendor.mjs, a changed pin or an intended model rebuild: rerun node scripts/notices.mjs and commit both files.
import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { PACKAGES, MODELS, NO_LICENSE_FILE } from "./vendor-pins.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), ".."), src = join(root, "src"), MANIFEST = "vendor.sha256", NOTICES = "THIRD-PARTY-NOTICES.md";
const sha256 = f => createHash("sha256").update(readFileSync(f)).digest("hex");

/** The manifest text for the files in <dir>/vendor and the models in <dir>/models. */
function manifestText(dir) {
  const v = join(dir, "vendor"), m = join(dir, "models");
  const rows = readdirSync(v).sort().map(f => `${sha256(join(v, f))}  vendor/${f}`);
  for (const { file } of MODELS) { if (!existsSync(join(m, file))) throw new Error(`models/${file} is missing: notices.mjs pins every model`); rows.push(`${sha256(join(m, file))}  models/${file}`); }
  return rows.join("\n") + "\n";
}
/** @returns {Map<string, string>} path → SHA-256, from vendor.sha256 */
export function readManifest(dir = src) {
  return new Map(readFileSync(join(dir, MANIFEST), "utf8").trim().split("\n").map(l => { const [h, p] = l.split(/\s+/); return [p, h]; }));
}

/**
 * Check the vendor/ and models/ files under root against the pins in vendor.sha256 (read from dir).
 * models: "require" every model must be there, "present" check those that are there, "skip" do not look.
 * @returns {string[]} one line per problem; empty when everything matches
 */
export function verifyVendor({ dir = src, root = dir, models = "present" } = {}) {
  const pins = readManifest(dir), bad = [];
  const have = existsSync(join(root, "vendor")) ? readdirSync(join(root, "vendor")).map(f => `vendor/${f}`) : [];
  for (const f of have) if (!pins.has(f)) bad.push(`${f}: not pinned in vendor.sha256 (add it to scripts/vendor-pins.mjs, then run node scripts/notices.mjs)`);
  for (const [p, h] of pins) {
    const isModel = p.startsWith("models/"); if (isModel && models === "skip") continue;
    const f = join(root, p);
    if (!existsSync(f)) { if (!isModel || models === "require") bad.push(`${p}: missing (run node scripts/fetch-vendor.mjs${p.endsWith("sr_x2.onnx") ? "; sr_x2.onnx comes from scripts/export-sr-model.py" : ""})`); continue; }
    const got = sha256(f);
    if (got !== h) bad.push(`${p}: SHA-256 ${got.slice(0, 12)}… is not the pinned ${h.slice(0, 12)}…` + (p.endsWith("sr_x2.onnx") ? " (a local export can differ byte for byte: after an intended rebuild run node scripts/notices.mjs)" : ""));
  }
  return bad;
}

/* ───────────── THIRD-PARTY-NOTICES.md ───────────── */
const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i;
function licenseText(dir) {
  const f = readdirSync(dir).filter(n => LICENSE_FILE.test(n)).sort()[0];
  return f ? readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n").trim() : null;
}
const repoUrl = pj => { const r = typeof pj.repository === "string" ? pj.repository : pj.repository && pj.repository.url; return r ? r.replace(/^git\+/, "").replace(/\.git$/, "").replace(/^git:\/\//, "https://").replace(/^github:/, "https://github.com/") : pj.homepage || ""; };
/** Packages esbuild put into a bundle, from its metafile: name → folder under node_modules. */
function bundled(nm, meta) {
  const names = new Set();
  for (const p of Object.keys(JSON.parse(readFileSync(meta, "utf8")).inputs)) { const m = p.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//); if (m) names.add(m[1]); }
  return [...names].sort().map(n => join(nm, n));
}

async function noticesText() {
  const nm = join(root, ".cache/node_modules"), meta = join(root, ".cache/quickhull.meta.json");
  if (!existsSync(nm) || !existsSync(meta)) throw new Error(".cache/node_modules or .cache/quickhull.meta.json is missing: run node scripts/fetch-vendor.mjs first");
  const out = ["# Third-party notices", "", "Generated by `node scripts/notices.mjs` from the pins in scripts/vendor-pins.mjs",
    "and the packages scripts/fetch-vendor.mjs installs. Do not edit by hand. The",
    "SHA-256 of every served file is in src/vendor.sha256. NOTICE says what each",
    "one is used for.", ""];
  const section = async (title, dir, files, extra = {}) => {
    const pj = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    let text = licenseText(dir), from = "package";
    if (!text && extra.licenseUrl) { const r = await fetch(extra.licenseUrl); if (!r.ok) throw new Error(`${extra.licenseUrl}: HTTP ${r.status}`); text = (await r.text()).replace(/\r\n/g, "\n").trim(); from = extra.licenseUrl; }
    if (!text && NO_LICENSE_FILE[pj.name]) { text = NO_LICENSE_FILE[pj.name]; from = "none"; }
    if (!text) throw new Error(`${pj.name}: no license file in the package: add a licenseUrl pin or a NO_LICENSE_FILE note in vendor-pins.mjs`);
    const declared = typeof pj.license === "object" && pj.license ? pj.license.type : pj.license;
    out.push(`## ${title} ${pj.version}`, "", `- License: ${extra.use || declared || extra.license}`, `- Source: ${repoUrl(pj)}`);
    if (files) out.push(`- Files: ${files}`);
    if (from === "none") { out.push("", text, ""); return; }
    if (from !== "package") out.push(`- License text: ${from} (the npm package ships none)`);
    out.push("", "```text", text, "```", "");
  };
  for (const p of PACKAGES) {
    if (p.tool) continue;
    const dir = join(nm, p.pkg), pj = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    if (pj.version !== p.version) throw new Error(`${p.pkg}: installed ${pj.version}, pinned ${p.version}: run node scripts/fetch-vendor.mjs`);
    if (p.bundle) for (const d of bundled(nm, meta)) await section(JSON.parse(readFileSync(join(d, "package.json"), "utf8")).name, d, `src/vendor/${p.bundle} (bundled)`);
    else await section(p.pkg, dir, Object.values(p.files).map(f => `src/vendor/${f}`).join(", "), p);
  }
  out.push("## Models", "", "| File | Model | License | Source |", "|---|---|---|---|",
    ...MODELS.map(m => `| src/models/${m.file} | ${m.name} | ${m.license} | ${m.source} |`), "",
    "Each model's license is stated by its source above; the Apache License 2.0", "text is at https://www.apache.org/licenses/LICENSE-2.0", "");
  return out.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check"), mi = process.argv.indexOf("--models"), models = mi > 0 ? process.argv[mi + 1] : "present";
  if (!check) {
    writeFileSync(join(root, NOTICES), await noticesText()); writeFileSync(join(src, MANIFEST), manifestText(src));
    console.log(`Wrote ${NOTICES} and src/${MANIFEST}`);
  } else {
    const bad = verifyVendor({ models });
    if (readFileSync(join(root, NOTICES), "utf8") !== await noticesText()) bad.push(`${NOTICES} is out of date: run node scripts/notices.mjs and commit it`);
    for (const l of bad) console.log("FAIL", l);
    console.log(bad.length ? `${bad.length} FAILED` : `notices and vendor hashes match (${readManifest().size} pinned files)`);
    process.exitCode = bad.length ? 1 : 0;
  }
}
